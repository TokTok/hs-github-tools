-- | The workflow dependency lockfile, .github/workflows/actions.lock, as
-- `gh actions-lock` writes it: which actions each workflow's steps use, and
-- the commit each of those actions is pinned to.
--
-- A combined lock holds the workflows of several repositories, named by their
-- path in a workspace ("btox/.github/workflows/ci.yml"), so that every
-- repository's lock can be cut from it with the same commits.
module GitHub.Types.ActionsLock
  ( ActionsLock (..)
  , Dependency (..)
  , actionKey
  , actionRepo
  , stepActions
  , renderLock
  , renameWorkflows
  , repoWorkflowKey
  , repoLock
  , repoProblems
  , combinedProblems
  ) where

import           Control.Monad     (guard, unless)
import           Data.Aeson        (FromJSON (..), Value (..), withObject,
                                    (.!=), (.:), (.:?))
import qualified Data.Aeson.KeyMap as KeyMap
import           Data.Char         (isHexDigit)
import           Data.List         (sort)
import           Data.Map.Strict   (Map)
import qualified Data.Map.Strict   as Map
import           Data.Maybe        (mapMaybe)
import qualified Data.Set          as Set
import           Data.Text         (Text)
import qualified Data.Text         as Text
import qualified Data.Vector       as V

data Dependency = Dependency
  { depRef     :: Text
  , depCommit  :: Text
  , depOwnerId :: Int
  , depRepoId  :: Int
  , depUses    :: [Text]
    -- ^ What a composite action uses in turn.
  } deriving (Eq, Show)

data ActionsLock = ActionsLock
  { lockWorkflows    :: Map Text [Text]
  , lockDependencies :: Map Text Dependency
  } deriving (Eq, Show)

lockVersion :: Text
lockVersion = "v0.0.3"

instance FromJSON Dependency where
  parseJSON = withObject "Dependency" $ \o -> Dependency
    <$> o .: "ref"
    <*> o .: "commit"
    <*> o .: "owner_id"
    <*> o .: "repo_id"
    <*> o .:? "uses" .!= []

instance FromJSON ActionsLock where
  parseJSON = withObject "ActionsLock" $ \o -> do
    version <- o .: "version"
    unless (version == lockVersion) . fail $
      "actions.lock version " <> Text.unpack version <> " isn't " <> Text.unpack lockVersion
    ActionsLock <$> o .: "workflows" <*> o .:? "dependencies" .!= Map.empty

-- | The lock in the layout `gh actions-lock` writes, so either tool can
-- update a lock without changing anything else in it.
renderLock :: ActionsLock -> Text
renderLock ActionsLock{..} = Text.unlines $
  [ "# This file is machine-generated by `gh actions-lock`."
  , "# Do not edit by hand; run `gh actions-lock` to update."
  , "# Docs: https://gh.io/actions-lockfile"
  , "version: " <> quote lockVersion
  , "workflows:"
  ] ++ concatMap workflow (Map.toList lockWorkflows)
    ++ (if Map.null lockDependencies then [] else "dependencies:" : concatMap dependency (Map.toList lockDependencies))
  where
    workflow (path, [])   = [indent 1 $ quote path <> ": []"]
    workflow (path, keys) = indent 1 (quote path <> ":") : list 2 keys
    dependency (key, Dependency{..}) =
      indent 1 (quote key <> ":")
      : map (indent 2)
        [ "ref: " <> quote depRef
        , "commit: " <> quote depCommit
        , "owner_id: " <> Text.pack (show depOwnerId)
        , "repo_id: " <> Text.pack (show depRepoId)
        ]
      ++ (if null depUses then [] else indent 2 "uses:" : list 3 depUses)
    list n = map (indent n . ("- " <>) . quote)
    indent n = (Text.replicate (4 * n) " " <>)
    quote t = "'" <> Text.replace "'" "''" t <> "'"

-- | Split a step's `uses:` into the action's path and its ref.
splitUses :: Text -> Maybe (Text, Text)
splitUses uses = case Text.breakOnEnd "@" uses of
  ("", _)       -> Nothing
  (pathAt, ref) -> Just (Text.dropEnd 1 pathAt, ref)

-- | The repository an action lives in, lowercased ("google/clusterfuzzlite"
-- for "google/clusterfuzzlite/actions/run_fuzzers").
actionRepo :: Text -> Text
actionRepo = Text.toLower . Text.intercalate "/" . take 2 . Text.splitOn "/"

-- | How actions.lock names the action a step uses: its repository and ref.
-- Local actions and containers aren't locked.
actionKey :: Text -> Maybe Text
actionKey uses
  | any (`Text.isPrefixOf` uses) ["./", "$/", "docker://"] = Nothing
  | otherwise = (\(path, ref) -> actionRepo path <> "@" <> ref) <$> splitUses uses

-- | The actions a workflow's steps use. Reusable workflows (jobs.<id>.uses)
-- aren't locked.
stepActions :: Value -> [Text]
stepActions (Object workflow) = Set.toList . Set.fromList $
  [ key
  | Just (Object jobs) <- [KeyMap.lookup "jobs" workflow]
  , Object job <- KeyMap.elems jobs
  , Just (Array steps) <- [KeyMap.lookup "steps" job]
  , Object step <- V.toList steps
  , Just (String uses) <- [KeyMap.lookup "uses" step]
  , Just key <- [actionKey uses]
  ]
stepActions _ = []

-- | A workflow's name in a combined lock, given its repository's path in the
-- workspace ("." for the workspace itself) and its file name.
repoWorkflowKey :: FilePath -> FilePath -> Text
repoWorkflowKey repo file = repoPrefix repo <> ".github/workflows/" <> Text.pack file

repoPrefix :: FilePath -> Text
repoPrefix "."  = ""
repoPrefix repo = Text.pack repo <> "/"

renameWorkflows :: (Text -> Maybe Text) -> ActionsLock -> ActionsLock
renameWorkflows rename lock = lock
  { lockWorkflows = Map.fromList . mapMaybe (\(k, v) -> (, v) <$> rename k) . Map.toList $ lockWorkflows lock }

-- | Drop the dependencies no workflow needs.
prune :: ActionsLock -> ActionsLock
prune lock@ActionsLock{..} = lock { lockDependencies = Map.restrictKeys lockDependencies needed }
  where
    needed = go Set.empty . concat $ Map.elems lockWorkflows
    go seen [] = seen
    go seen (k:ks)
      | k `Set.member` seen = go seen ks
      | otherwise = go (Set.insert k seen) (maybe [] depUses (Map.lookup k lockDependencies) ++ ks)

-- | A repository's lock, cut from a combined lock.
repoLock :: FilePath -> ActionsLock -> ActionsLock
repoLock repo = prune . renameWorkflows own
  where
    -- The workspace's own workflows have no prefix, so check what's left.
    own key = do
      path <- Text.stripPrefix (repoPrefix repo) key
      guard $ ".github/workflows/" `Text.isPrefixOf` path
      return path

-- | What's wrong with a repository's actions.lock (Nothing if it has none),
-- given what its workflows use and the combined lock it should be cut from.
repoProblems :: ActionsLock -> FilePath -> Maybe ActionsLock -> Map Text [Text] -> [Text]
repoProblems combined repo lock used =
  [ path <> " uses " <> showKeys (Map.lookup path used) <> ", but the combined lock has "
      <> showKeys (Map.lookup path (lockWorkflows expected))
  | path <- differences used (lockWorkflows expected) ]
  ++ case lock of
    Nothing -> ["There is no .github/workflows/actions.lock."]
    Just actual ->
      [ path <> ": actions.lock has " <> showKeys (Map.lookup path (lockWorkflows actual))
          <> ", the combined lock has " <> showKeys (Map.lookup path (lockWorkflows expected))
      | path <- differences (lockWorkflows actual) (lockWorkflows expected) ]
      ++ [ key <> ": actions.lock has " <> showDep (Map.lookup key (lockDependencies actual))
             <> ", the combined lock has " <> showDep (Map.lookup key (lockDependencies expected))
         | key <- differences (lockDependencies actual) (lockDependencies expected) ]
  where
    expected = repoLock repo combined
    showKeys = maybe "nothing" (Text.intercalate ", ")
    showDep = maybe "nothing" depCommit

-- | What's wrong with a combined lock: every action must be pinned, and each
-- action's repository used at one ref in all workflows.
combinedProblems :: ActionsLock -> [Text]
combinedProblems ActionsLock{..} =
  [ key <> " has no pinned commit"
  | key <- Set.toList . Set.fromList $ concat (Map.elems lockWorkflows) ++ concatMap depUses (Map.elems lockDependencies)
  , maybe True (not . isPinned . depCommit) (Map.lookup key lockDependencies) ]
  ++ [ repo <> " is used at " <> Text.intercalate " and " (map showRef (Map.toList refs))
     | (repo, refs) <- Map.toList refsByRepo, Map.size refs > 1 ]
  where
    refsByRepo = Map.fromListWith (Map.unionWith (++))
      [ (actionRepo path, Map.singleton ref [workflow])
      | (workflow, keys) <- Map.toList lockWorkflows, Just (path, ref) <- map splitUses keys ]
    showRef (ref, workflows)
      | length workflows > 3 = ref <> " (" <> Text.pack (show (length workflows)) <> " workflows)"
      | otherwise = ref <> " (" <> Text.intercalate ", " (sort workflows) <> ")"

-- | Whether a lockfile commit is a full SHA-1, written "sha1-<40 hex digits>".
isPinned :: Text -> Bool
isPinned commit = case Text.stripPrefix "sha1-" commit of
  Just sha -> Text.length sha == 40 && Text.all isHexDigit sha
  Nothing  -> False

differences :: (Ord k, Eq v) => Map k v -> Map k v -> [k]
differences a b =
  [ k | k <- Set.toList (Map.keysSet a <> Map.keysSet b), Map.lookup k a /= Map.lookup k b ]
